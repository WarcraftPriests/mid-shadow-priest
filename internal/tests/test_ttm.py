def test_convert_builds_transforms_file(tmp_path, monkeypatch):
    # Work in the talents directory
    root_dir = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
    monkeypatch.chdir(root_dir)
    ttm = load_ttm_module(root_dir)
    profile = tmp_path / "test_profile.simc"
    # craft a line that will be accepted (has 3 idols and >=9 bottom talents)
    idols = "idol_of_yshaarj idol_of_nzoth idol_of_yogg"
    bottoms = " ".join([f"{t}:1" for t in [
        "mindbender",
        "deathspeaker",
        "death_and_madness",
        "mind_devourer",
        "auspicious_spirits",
        "inescapable_torment",
        "deaths_torment",
        "screams_of_the_void",
        "idol_of_cthun",
    ]])
    # include choice nodes: invoked_nightmare, improved_voidform, minds_eye
    line = (
        f"Solved loadout voidform invoked_nightmare improved_voidform minds_eye {idols} {bottoms} 22111 profileset.\"VF\"+=\"SOME\"\n"
    )
    content = [line]
    (tmp_path / "dummy").mkdir(exist_ok=True)
    # write file in tmp dir and run conversion on that path
    with open(profile, "w", encoding="utf8") as f:
        f.writelines(content)

    ttm.convert_builds(str(profile))

    # verify signature and transformed content
    with open(profile, "r", encoding="utf8") as f:
        out = f.read()
    assert out.startswith("# Automatically generated by ttm.py\n")
    # Profileset key should have idols appended
    assert 'profileset."VF_yshaarj_nzoth_yogg' in out
    # numeric cluster replaced by suffix pieces (IN and IV and ME expected)
    assert "_IN_" in out and "_IV" in out and "_ME" in out


def test_duplicate_and_make_build_files(tmp_path, monkeypatch):
    root_dir = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
    # load module (imports config relative to talents)
    ttm = load_ttm_module(root_dir)

    # Create hero files and base.simc inside tmp_path so tests do not pollute repo
    ar_file = tmp_path / "hero_AR.simc"
    vw_file = tmp_path / "hero_VW.simc"
    ar_file.write_text('profileset."T1"+="spec1 minds_eye _ME"\n', encoding="utf8")
    vw_file.write_text('profileset."T2"+="spec2"\n', encoding="utf8")

    # ensure base.simc exists in tmp_path
    base_file = tmp_path / "base.simc"
    base_file.write_text("BASELINE\n", encoding="utf8")

    # prepare builds dir in tmp_path and a stray file to be removed
    builds_dir = tmp_path / "builds"
    builds_dir.mkdir(exist_ok=True)
    (builds_dir / "old.simc").write_text("OLD\n", encoding="utf8")

    # monkeypatch config used by duplicate_builds
    ttm.config = {"hero": {"AR": {"HERO1": "hero_tal=1"}, "VW": {"VH1": "hero_v=1"}}}

    # change cwd to tmp_path so ttm writes its outputs there
    monkeypatch.chdir(str(tmp_path))

    # run duplication (writes hero_*_duplicated.simc into tmp_path)
    ttm.duplicate_builds()
    assert (tmp_path / "hero_AR_duplicated.simc").exists()
    assert (tmp_path / "hero_VW_duplicated.simc").exists()

    # run make_build_files
    ttm.make_build_files()
    # expect at least one batch file created in builds_dir
    files = [f.name for f in builds_dir.iterdir() if f.name.startswith("talents_")]
    assert len(files) >= 1
    # check that baseline was written into the first batch file
    with open(builds_dir / files[0], "r", encoding="utf8") as f:
        batch_content = f.read()
    assert "BASELINE" in batch_content


