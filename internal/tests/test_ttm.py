def test_runtime_registration_and_restore():
    root = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
    ttm = load_ttm_module(root)
    # save originals
    orig_pairs = list(ttm.CHOICE_NODE_PAIRS)
    orig_singletons = list(ttm.CHOICE_NODE_SINGLETONS)
    orig_idols = list(ttm.IDOLS)
    try:
        # register new entries
        ttm.register_choice_pair(("alpha", "beta"), ("A", "B"))
        ttm.register_choice_singleton("gamma", "G")
        ttm.register_idol("test_idol")
        assert (("alpha", "beta"), ("A", "B")) in ttm.CHOICE_NODE_PAIRS
        assert ("gamma", "G") in ttm.CHOICE_NODE_SINGLETONS
        assert "test_idol" in ttm.IDOLS
    finally:
        # restore originals to avoid cross-test pollution
        ttm.CHOICE_NODE_PAIRS[:] = orig_pairs
        ttm.CHOICE_NODE_SINGLETONS[:] = orig_singletons
        ttm.IDOLS[:] = orig_idols


def test_load_config_applies_talents_section(tmp_path):
    root = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
    ttm = load_ttm_module(root)
    # prepare a temp config with a talents section
    cfg = {
        "talents": {
            "choice_pairs": [
                {"keywords": ["foo", "bar"], "suffixes": ["F", "B"]}
            ],
            "choice_singletons": [{"keyword": "baz", "suffix": "Z"}],
            "idols": ["cfg_idol"],
        }
    }
    cfg_path = tmp_path / "cfg.yml"
    import yaml as _yaml

    cfg_path.write_text(_yaml.dump(cfg), encoding="utf8")

    # save originals
    orig_pairs = list(ttm.CHOICE_NODE_PAIRS)
    orig_singletons = list(ttm.CHOICE_NODE_SINGLETONS)
    orig_idols = list(ttm.IDOLS)
    try:
        # load config from the temporary file (should apply talents section)
        ttm.load_config(str(cfg_path))
        assert (("foo", "bar"), ("F", "B")) in ttm.CHOICE_NODE_PAIRS
        assert ("baz", "Z") in ttm.CHOICE_NODE_SINGLETONS
        assert "cfg_idol" in ttm.IDOLS
    finally:
        # restore
        ttm.CHOICE_NODE_PAIRS[:] = orig_pairs
        ttm.CHOICE_NODE_SINGLETONS[:] = orig_singletons
        ttm.IDOLS[:] = orig_idols
        ttm.config = None
