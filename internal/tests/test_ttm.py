import os
import importlib.util


def load_ttm_module(root_dir):
    ttm_path = os.path.join(root_dir, "talents/ttm.py")
    # ttm.py opens ../config.yml relative to the current working directory at import
    talents_dir = os.path.join(root_dir, "talents")
    os.makedirs(talents_dir, exist_ok=True)
    orig_cwd = os.getcwd()
    try:
        os.chdir(talents_dir)
        # ensure a minimal config.yml exists one level up
        config_path = os.path.join(root_dir, "config.yml")
        if not os.path.exists(config_path):
            with open(config_path, "w", encoding="utf8") as cf:
                cf.write("hero:\n  AR: {}\n  VW: {}\n")
        spec = importlib.util.spec_from_file_location("ttm", ttm_path)
        ttm = importlib.util.module_from_spec(spec)
        spec.loader.exec_module(ttm)
    finally:
        os.chdir(orig_cwd)
    return ttm


def test_generate_suffix_and_talents_class(tmp_path):
    root_dir = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
    ttm = load_ttm_module(root_dir)
    assert ttm.generate_suffix(["A", "B"]) == "A_B"
    # empty
    assert ttm.generate_suffix([]) == ""
    # Talents class
    t = ttm.Talents("a", "b", "c")
    assert t.st == "a" and t.ct == "b" and t.ht == "c"


